"""AgenEKG exploratory API-documentation arm (preregistration, deviation of 21 November 2026).

The same harness as `agenekg_agen.py` with one difference: the system prompt is extended with the API summary
`agenekg_api_ringkas.txt` (generated by `agenekg_api_ringkas.py` inside the container). Same arguments:

    python -X utf8 analysis/agenekg_agen_api.py --tugas analysis/agenekg_tugas.json --model <id> \
        --ulang-ke 1 --keluar <output folder>
"""
from pathlib import Path

import agenekg_agen

RINGKASAN_API = Path(__file__).with_name("agenekg_api_ringkas.txt")


def main():
    agenekg_agen.SISTEM = agenekg_agen.SISTEM + "\n\n" + RINGKASAN_API.read_text(encoding="utf-8")
    agenekg_agen.main()


if __name__ == "__main__":
    main()
